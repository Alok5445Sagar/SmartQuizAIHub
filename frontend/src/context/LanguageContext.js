const defaultLanguageContextValue = {
  language: 'en',
  setLanguage: () => {},
  t: (key) => translations.en[key] || key,
  availableLanguages: [
    { code: 'en', label: 'English' },
    { code: 'es', label: 'Spanish' },
    { code: 'fr', label: 'French' },
    { code: 'ro', label: 'Romanian' },
  ],
};

const LanguageContext = createContext(defaultLanguageContextValue);

export function LanguageProvider({ children }) {
  const { user, setPreferredLanguage } = useAuth();
  const initial = (localStorage.getItem(LANG_STORAGE_KEY)
    || readStoredUserPreferredLanguage()
    || 'en').toLowerCase();
  const [language, setLanguageState] = useState(['en', 'es', 'fr', 'ro'].includes(initial) ? initial : 'en');

  useEffect(() => {
    const preferred = (user?.preferredLanguage || '').toLowerCase();
    if (!preferred) return;
    if (!['en', 'es', 'fr', 'ro'].includes(preferred)) return;
    if (preferred === language) return;
    setLanguageState(preferred);
    localStorage.setItem(LANG_STORAGE_KEY, preferred);
  }, [user?.preferredLanguage, language]);

  const setLanguage = (code) => {
    const normalized = (code || 'en').toLowerCase();
    const safe = ['en', 'es', 'fr', 'ro'].includes(normalized) ? normalized : 'en';
    setLanguageState(safe);
    localStorage.setItem(LANG_STORAGE_KEY, safe);

    if (user?.enterpriseId && typeof setPreferredLanguage === 'function') {
      setPreferredLanguage(safe).catch(() => {
        // Keep UI responsive even if preference persistence fails.
      });
    }
  };

  const value = useMemo(() => ({
    language,
    setLanguage,
    t: (key) => translations[language]?.[key] || translations.en[key] || key,
    availableLanguages: [
      { code: 'en', label: 'English' },
      { code: 'es', label: 'Spanish' },
      { code: 'fr', label: 'French' },
      { code: 'ro', label: 'Romanian' },
    ],
  }), [language]);

  return <LanguageContext.Provider value={value}>{children}</LanguageContext.Provider>;
}

export function useLanguage() {
  return useContext(LanguageContext) || defaultLanguageContextValue;
}
